/**
 * License badge per Tools card (see licenseBadges.ts) and the "Open weights
 * only" filter. Every card gets one badge:
 *
 *   open    every model it needs is under an open license (commercial OK)
 *   cap     open weights under a revenue-capped community license
 *           (Krea 2, FLUX.3 Klein, LTX-2, LTXV 0.9.8, Stable Audio 3)
 *   nc      needs non-commercial weights
 *   region  needs MiniMax H3 (territory carve-out)
 *   check   a model's terms could not be confirmed
 *
 * Every tool runs on downloadable weights (no partner/API nodes), so all
 * of them are open weights in the contest sense. The toggle ("Commercial
 * use OK", internal name openWeightsOnly) keeps open + cap: the cap only
 * limits commercial use by larger companies, which the badge and tooltip
 * state. nc, region and check are hidden because they bar or may bar
 * commercial use.
 *
 * Action and catalog cards come from toolWeightClasses.json, generated by
 * openWeightsGen.ts from MODEL_FAMILIES matched against each tool's shipped
 * graph (the toolsDoc data; that module reads the filesystem, so the client
 * gets the result as JSON). src/__tests__/openWeights.test.ts keeps it in
 * sync. A card whose hub data already says nc stays nc everywhere, engine
 * cards included (their nc flag reflects the engine that runs). Engine cards
 * (templates, apps, storyboard, pipelines) otherwise use the EDIT_ENGINES
 * licenses. Folded engine-group cards carry their best engine's badge.
 * Pure (no React); storage is injected and never throws.
 */

import { STORYBOARD_KEY, type HubCard } from "./hub";
import weightClassesJson from "./toolWeightClasses.json";
import { isH3Model } from "./h3License";
import {
  EDIT_ENGINES,
  SINGLE_ENGINES,
  engineBadge,
  engineSources,
  getTemplate,
} from "./templates";
import type { EditEngineId } from "./templates";
import { appEngines, getApp } from "./apps";
import { STORYBOARD_ENGINES } from "./storyboard";
import { CLICK_TO_AD_KEY, CLIPCUT_KEY, URBAN_CUTS_KEY } from "./pipelineCards";
import {
  BADGE_LABEL,
  badgeTooltip,
  bestBadge,
  isOpenWeightsBadge,
  sourceFor,
  worstBadge,
  type BadgeSource,
  type LicenseBadge,
} from "./licenseBadges";
import { H3_MODEL_NAME } from "./h3License";

/** Kept as an alias: the card's license badge. */
export type WeightsClass = LicenseBadge;

export const WEIGHTS_LABEL: Record<LicenseBadge, string> = BADGE_LABEL;

export interface WeightClassFile {
  note: string;
  classes: Record<string, LicenseBadge>;
  sources: Record<string, BadgeSource[]>;
}

const FILE = weightClassesJson as unknown as WeightClassFile;
const WEIGHT_CLASSES = FILE.classes;
const WEIGHT_SOURCES = FILE.sources ?? {};

// ---------------------------------------------------------------------------
// Client side
// ---------------------------------------------------------------------------

/** Edit engines a non-tool card picks from (first installed wins). */
function cardEngines(card: HubCard): EditEngineId[] | null {
  if (card.kind === "template") return getTemplate(card.id)?.engines ?? null;
  if (card.kind === "app") {
    const app = getApp(card.id);
    return app ? appEngines(app) : null;
  }
  if (card.key === STORYBOARD_KEY) return STORYBOARD_ENGINES;
  if (
    card.key === CLICK_TO_AD_KEY ||
    card.key === CLIPCUT_KEY ||
    card.key === URBAN_CUTS_KEY
  )
    return SINGLE_ENGINES;
  return null;
}

/** Engine card: the best engine that is not non-commercial. */
function bestUsableEngine(engines: EditEngineId[]): EditEngineId | null {
  const usable = engines.filter((id) => EDIT_ENGINES[id]?.license !== "nc");
  if (!usable.length) return null;
  const best = bestBadge(usable.map((id) => engineBadge(EDIT_ENGINES[id])));
  return usable.find((id) => engineBadge(EDIT_ENGINES[id]) === best) ?? null;
}

/** Click to Ad always renders its clips with LTX-2.5 (adLtx.ts). */
function adVideoBadge(card: HubCard): LicenseBadge | null {
  return card.key === CLICK_TO_AD_KEY
    ? (WEIGHT_CLASSES["action:ltx25_animate"] ?? null)
    : null;
}

function addSoundBadge(card: HubCard): LicenseBadge | null {
  const app = card.kind === "app" ? getApp(card.id) : undefined;
  return app?.sound && app.autoAnimate
    ? (WEIGHT_CLASSES["action:add_sound"] ?? "nc")
    : null;
}

export function weightsClass(card: HubCard): LicenseBadge {
  if (card.weights) return card.nc ? "nc" : card.weights;
  const known = WEIGHT_CLASSES[card.key];
  if (known) return card.nc ? "nc" : known;
  if (isH3Model(card.model)) return "region";
  const engines = cardEngines(card);
  if (engines && engines.length) {
    const best = bestUsableEngine(engines);
    if (!best) return "nc";
    // The hub nc flag marks the engine that actually runs (first installed).
    if (card.nc) return "nc";
    const badge = engineBadge(EDIT_ENGINES[best]);
    // An app that auto-adds sound always runs the Add Sound model too.
    const extra = [addSoundBadge(card), adVideoBadge(card)].filter(
      (b): b is LicenseBadge => !!b,
    );
    return extra.length ? worstBadge([badge, ...extra]) : badge;
  }
  return card.nc ? "nc" : "open";
}

/** The licenses behind a card's badge (tooltip / runner links). */
export function weightsSources(card: HubCard): BadgeSource[] {
  const badge = weightsClass(card);
  if (badge === "open") return [];
  if (card.weightSources) return card.weightSources;
  const known = WEIGHT_SOURCES[card.key];
  if (known && WEIGHT_CLASSES[card.key] === badge) return known;
  if (badge === "region")
    return [sourceFor(`${H3_MODEL_NAME} Community License`)];
  const engines = cardEngines(card);
  if (engines && engines.length) {
    if (addSoundBadge(card) === badge)
      return WEIGHT_SOURCES["action:add_sound"] ?? [];
    if (adVideoBadge(card) === badge)
      return WEIGHT_SOURCES["action:ltx25_animate"] ?? [];
    const best = bestUsableEngine(engines);
    if (best) return engineSources(EDIT_ENGINES[best]);
  }
  return [];
}

/**
 * Tooltip for a card's badge. Catalog cards with a registry note use it
 * (it names the LoRA and base terms), else the license terms summary.
 */
export function weightsTooltip(card: HubCard): string {
  const badge = weightsClass(card);
  const sources = weightsSources(card);
  if (card.licenseNote && badge !== "open") {
    const urls = sources.map((s) => s.url).filter(Boolean);
    return [card.licenseNote, ...new Set(urls)].join("\n");
  }
  return badgeTooltip(badge, sources);
}

export function isOpenWeights(card: HubCard): boolean {
  return isOpenWeightsBadge(weightsClass(card));
}

/** Cards shown with the toggle on (placeholders are not tools; kept as-is). */
export function filterOpenWeights(
  cards: HubCard[],
  openOnly: boolean,
): HubCard[] {
  if (!openOnly) return cards;
  return cards.filter((c) => c.kind === "placeholder" || isOpenWeights(c));
}

/** Real tools only: "coming soon" placeholders are not counted. */
export function openWeightsCount(cards: HubCard[]): {
  open: number;
  total: number;
} {
  const tools = cards.filter((c) => c.kind !== "placeholder");
  return { open: tools.filter(isOpenWeights).length, total: tools.length };
}

export function openWeightsSummary(cards: HubCard[]): string {
  const { open, total } = openWeightsCount(cards);
  return `${open} of ${total} tools allow commercial use`;
}

// ---------------------------------------------------------------------------
// Persistence
// ---------------------------------------------------------------------------

export const OPEN_WEIGHTS_STORAGE_KEY = "adrift.tools.openWeightsOnly.v1";

type StorageLike = Pick<Storage, "getItem" | "setItem">;

export function readOpenWeightsOnly(storage: StorageLike | null): boolean {
  try {
    return storage?.getItem(OPEN_WEIGHTS_STORAGE_KEY) === "1";
  } catch {
    return false;
  }
}

export function writeOpenWeightsOnly(
  storage: StorageLike | null,
  on: boolean,
): void {
  try {
    storage?.setItem(OPEN_WEIGHTS_STORAGE_KEY, on ? "1" : "0");
  } catch {
    /* private mode / blocked storage */
  }
}
