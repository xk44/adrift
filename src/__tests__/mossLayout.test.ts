/** MOSS-Image layout boxes: byte-exact port of ComfyUI MOSSImageLayoutPrompt. */
import fs from "fs";
import path from "path";
import { describe, expect, it } from "vitest";
import type { Workflow } from "@/types";
import { injectParams } from "@/lib/oj/engine";
import { discoverT2ISlots } from "@/lib/oj/discovery";
import {
  MOSS_LAYOUT_MAX_BOXES,
  buildMossLayoutPrompt,
  gridBox,
  mossLayoutCanvas,
  sanitizeMossLayout,
  type MossLayoutBox,
} from "@/lib/oj/mossLayout";

const load = (name: string): Workflow => {
  const g = JSON.parse(
    fs.readFileSync(
      path.join(process.cwd(), "public/workflows/packs/moss-image", `${name}.json`),
      "utf-8",
    ),
  );
  delete g._meta;
  return g;
};

const ok = (raw: unknown): MossLayoutBox[] => {
  const r = sanitizeMossLayout(raw);
  if ("error" in r) throw new Error(r.error);
  return r.boxes;
};

// Expected strings generated by running the real ComfyUI node
// (comfy_extras/nodes_moss_image.py, ComfyUI v0.42) on the equivalent
// Create Bounding Boxes elements.
const FIXTURES: Array<{
  prompt: string;
  boxes: unknown[];
  width: number;
  height: number;
  grids: number[][];
  expected: string;
}> = [
  {
    prompt: "  a cozy cafe, film photo ",
    width: 1024,
    height: 1024,
    boxes: [
      { x: 0.05, y: 0.1, w: 0.4, h: 0.5, kind: "character", caption: "a barista in a green apron", palette: ["#2e7d32", "F5F5DC"] },
      { x: 0.333, y: 0.7, w: 0.334, h: 0.2, kind: "text", caption: "chalk sign", text: "Café ☕ 8am" },
      { x: 0, y: 0, w: 1, h: 1, caption: "warm light" },
    ],
    grids: [[100, 50, 600, 450], [700, 333, 900, 667], [0, 0, 1000, 1000]],
    expected:
      '{"summary":{"caption":"a cozy cafe, film photo"},"items":[{"label":"character","caption":"a barista in a green apron","palette":["#2E7D32","#F5F5DC"],"bbox":[-410,-461,103,-51]},{"label":"text","caption":"chalk sign","text":"Café ☕ 8am","bbox":[204,-172,410,172]},{"label":"object","caption":"warm light","bbox":[-512,-512,512,512]}],"bbox_coord_space":"abs_centralized","bbox_format":"yxyx"}',
  },
  {
    prompt: "street",
    width: 1360,
    height: 768,
    boxes: [{ x: 0.457, y: 0.123, w: 0.542, h: 0.666, kind: "object", caption: "a red bus" }],
    grids: [[123, 457, 789, 999]],
    expected:
      '{"summary":{"caption":"street"},"items":[{"label":"object","caption":"a red bus","bbox":[-290,-59,222,679]}],"bbox_coord_space":"abs_centralized","bbox_format":"yxyx"}',
  },
  {
    prompt: "odd",
    width: 1023,
    height: 777,
    boxes: [
      { x: 0.001, y: 0.001, w: 0.332, h: 0.998, caption: "tree" },
      { x: 0.5, y: 0.5, w: 0.001, h: 0.001, kind: "character", caption: "dot" },
    ],
    grids: [[1, 1, 999, 333], [500, 500, 501, 501]],
    expected:
      '{"summary":{"caption":"odd"},"items":[{"label":"object","caption":"tree","bbox":[-388,-510,389,-170]},{"label":"character","caption":"dot","bbox":[0,0,2,2]}],"bbox_coord_space":"abs_centralized","bbox_format":"yxyx"}',
  },
];

describe("MOSS layout prompt (port of MOSSImageLayoutPrompt)", () => {
  it.each(FIXTURES.map((f, i) => [i, f] as const))("fixture %i matches the ComfyUI node byte for byte", (_i, f) => {
    const boxes = ok(f.boxes);
    expect(boxes.map(gridBox)).toEqual(f.grids);
    expect(buildMossLayoutPrompt(f.prompt, boxes, f.width, f.height)).toBe(f.expected);
  });

  it("no boxes returns the prompt untouched (not stripped)", () => {
    expect(buildMossLayoutPrompt("  plain  ", [], 1024, 1024)).toBe("  plain  ");
  });

  it("grid snap uses Python banker's rounding", () => {
    // 0.0125 * 1000 = 12.5 -> 12 (even), 0.0135 * 1000 = 13.5 -> 14
    expect(gridBox({ x: 0.0135, y: 0.0125, w: 0.1, h: 0.1 }).slice(0, 2)).toEqual([12, 14]);
  });
});

describe("sanitizeMossLayout", () => {
  it("absent is an empty layout", () => {
    expect(ok(undefined)).toEqual([]);
    expect(ok(null)).toEqual([]);
  });

  it.each([
    ["not an array", { x: 0 }],
    ["too many boxes", Array.from({ length: MOSS_LAYOUT_MAX_BOXES + 1 }, () => ({ x: 0, y: 0, w: 0.1, h: 0.1, caption: "a" }))],
    ["non-number coords", [{ x: "0", y: 0, w: 0.1, h: 0.1, caption: "a" }]],
    ["outside canvas", [{ x: 0.5, y: 0, w: 0.6, h: 0.1, caption: "a" }]],
    ["zero size", [{ x: 0, y: 0, w: 0, h: 0.1, caption: "a" }]],
    ["bad kind", [{ x: 0, y: 0, w: 0.1, h: 0.1, kind: "logo", caption: "a" }]],
    ["missing caption", [{ x: 0, y: 0, w: 0.1, h: 0.1 }]],
    ["text without text", [{ x: 0, y: 0, w: 0.1, h: 0.1, kind: "text", caption: "sign" }]],
    ["bad palette", [{ x: 0, y: 0, w: 0.1, h: 0.1, caption: "a", palette: ["red"] }]],
  ])("rejects %s", (_name, raw) => {
    expect("error" in sanitizeMossLayout(raw)).toBe(true);
  });

  it("caps the palette at 5 and uppercases with #", () => {
    const [b] = ok([{ x: 0, y: 0, w: 0.1, h: 0.1, caption: "a", palette: ["aaaaaa", "#bbbbbb", "cccccc", "dddddd", "eeeeee", "ffffff"] }]);
    expect(b.palette).toEqual(["#AAAAAA", "#BBBBBB", "#CCCCCC", "#DDDDDD", "#EEEEEE"]);
  });

  it("text boxes may omit the caption", () => {
    const [b] = ok([{ x: 0, y: 0, w: 0.5, h: 0.2, kind: "text", text: "OPEN" }]);
    expect(b).toMatchObject({ kind: "text", caption: "", text: "OPEN" });
  });
});

describe("MOSS layout through injectParams", () => {
  it("t2i: positive prompt becomes layout JSON sized to the injected canvas", () => {
    const wf = load("t2i");
    const slots = discoverT2ISlots(wf);
    const boxes = ok([{ x: 0, y: 0, w: 0.5, h: 1, caption: "a fox" }]);
    injectParams(wf, slots, { ar: "16:9", mossLayout: boxes }, "a forest", "", 1);
    const canvas = mossLayoutCanvas(wf)!;
    expect(canvas.width).toBeGreaterThan(canvas.height);
    const text = String(wf[slots.posTextId].inputs[slots.posTextInputName ?? "text"]);
    const layout = JSON.parse(text);
    expect(layout.summary.caption).toBe("a forest");
    const hh = Math.floor(canvas.height / 2);
    const hw = Math.floor(canvas.width / 2);
    expect(layout.items[0].bbox).toEqual([-hh, -hw, canvas.height - hh, Math.ceil(canvas.width / 2) - hw]);
  });

  it("t2i without boxes keeps the plain prompt", () => {
    const wf = load("t2i");
    const slots = discoverT2ISlots(wf);
    injectParams(wf, slots, {}, "a forest", "", 1);
    expect(wf[slots.posTextId].inputs[slots.posTextInputName ?? "text"]).toBe("a forest");
  });

  it("i2i has no latent canvas, so layout is not applied", () => {
    expect(mossLayoutCanvas(load("i2i"))).toBeNull();
    expect(mossLayoutCanvas(load("t2i"))).not.toBeNull();
  });
});
