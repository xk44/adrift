/**
 * Card counts of the Tools page grid, written to src/lib/tools/hubCounts.json
 * so public copy (the export README) states the same numbers as the app.
 * Regenerate: UPDATE_TOOLS_DOC=1 vitest run src/__tests__/hubCounts.test.ts
 */
import { describe, it, expect } from "vitest";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { getEditTools, toPublicTool } from "@/lib/tools/editTools";
import { buildToolCards, type CatalogTool } from "@/lib/tools/toolsPage";
import { buildHubCards } from "@/lib/tools/hub";
import { foldEngineGroups } from "@/lib/tools/engineGroups";
import { isGridCard } from "@/lib/tools/toolRegistry";
import { openWeightsCount } from "@/lib/tools/openWeights";

const JSON_PATH = path.resolve(__dirname, "../lib/tools/hubCounts.json");

/** The grid as ToolsPage builds it, with every catalog tool installed. */
function gridCards() {
  const catalog = getEditTools().map((t) =>
    toPublicTool(t, {
      installed: true,
      keepFramingInstalled: true,
      speedInstalled: true,
      packAvailable: true,
    }),
  ) as unknown as CatalogTool[];
  const packIds = new Set<string>();
  const toolCards = buildToolCards({ catalog, packIds, editLoras: null });
  const cards = buildHubCards({
    toolCards,
    ctx: { catalog, packIds, editLoras: null },
  });
  return foldEngineGroups(cards).filter((c) => isGridCard(c.key));
}

describe("hubCounts.json", () => {
  it("matches the Tools page grid", () => {
    const grid = gridCards();
    const appTemplates = grid.filter((c) => c.kind === "app").length;
    // Multi-step tools and templates chain other tools' graphs, so they have
    // no row of their own in docs/TOOLS.md; every other tool card runs one
    // graph (an engine picker folds several TOOLS.md rows into one card).
    const chainedTools = grid.filter(
      (c) => c.kind === "special" || c.kind === "template",
    ).length;
    const counts = {
      note: "Generated by src/__tests__/hubCounts.test.ts. Do not edit by hand: run `UPDATE_TOOLS_DOC=1 vitest run src/__tests__/hubCounts.test.ts`.",
      cards: grid.length,
      tools: grid.length - appTemplates,
      graphTools: grid.length - appTemplates - chainedTools,
      chainedTools,
      appTemplates,
      commercialOk: openWeightsCount(grid).open,
    };
    expect(counts.tools).toBeGreaterThan(0);
    expect(counts.appTemplates).toBeGreaterThan(0);
    const text = JSON.stringify(counts, null, 2) + "\n";
    if (process.env.UPDATE_TOOLS_DOC) writeFileSync(JSON_PATH, text);
    expect(readFileSync(JSON_PATH, "utf8")).toBe(text);
  });
});
