import { describe, it, expect } from "vitest";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { buildToolDocRows, MODEL_FAMILIES } from "@/lib/tools/toolsDoc";
import { getEditTools, toPublicTool } from "@/lib/tools/editTools";
import {
  ACTION_TOOLS,
  buildToolCards,
  type CatalogTool,
} from "@/lib/tools/toolsPage";
import { buildHubCards, type HubCard } from "@/lib/tools/hub";
import { APP_TEMPLATES } from "@/lib/tools/apps";
import { TEMPLATES } from "@/lib/tools/templates";
import {
  buildWeightTable,
  classifyDocRow,
  familyBadge,
  isRegionRestrictedFamily,
} from "@/lib/tools/openWeightsGen";
import {
  OPEN_WEIGHTS_STORAGE_KEY,
  filterOpenWeights,
  isOpenWeights,
  openWeightsCount,
  openWeightsSummary,
  readOpenWeightsOnly,
  weightsClass,
  weightsTooltip,
  writeOpenWeightsOnly,
  type WeightClassFile,
} from "@/lib/tools/openWeights";
import type { Workflow } from "@/types";

const ROOT = path.resolve(__dirname, "../..");
const WF_DIR = path.join(ROOT, "public/workflows");
const JSON_PATH = path.join(ROOT, "src/lib/tools/toolWeightClasses.json");

function loadWorkflow(rel: string): Workflow | null {
  const p = path.join(WF_DIR, rel);
  if (!existsSync(p)) return null;
  return JSON.parse(readFileSync(p, "utf8")) as Workflow;
}

const { rows } = buildToolDocRows(loadWorkflow);
const outpaintKeys = getEditTools()
  .filter((t) => t.outpaint != null)
  .map((t) => `catalog:${t.id}`);
const table = buildWeightTable({
  rows,
  actionTools: ACTION_TOOLS,
  load: loadWorkflow,
  outpaintKeys,
});
const generated = table.classes;

/** Every registry tool, as the server lists it with everything installed. */
const catalog = getEditTools().map((t) =>
  toPublicTool(t, {
    installed: true,
    keepFramingInstalled: true,
    speedInstalled: true,
    packAvailable: true,
  }),
) as unknown as CatalogTool[];
const ctx = { catalog, packIds: new Set<string>(), editLoras: null };
const cards: HubCard[] = buildHubCards({
  toolCards: buildToolCards({ catalog, packIds: ctx.packIds, editLoras: null }),
  ctx,
});
const byKey = new Map(cards.map((c) => [c.key, c]));

describe("toolWeightClasses.json", () => {
  it("is in sync with MODEL_FAMILIES via the toolsDoc rows", () => {
    const file: WeightClassFile = {
      note: "Generated by src/__tests__/openWeights.test.ts from src/lib/tools/toolsDoc.ts. Do not edit by hand: run `UPDATE_TOOLS_DOC=1 vitest run src/__tests__/openWeights.test.ts`.",
      classes: generated,
      sources: table.sources,
    };
    const text = `${JSON.stringify(file, null, 2)}\n`;
    if (process.env.UPDATE_TOOLS_DOC) writeFileSync(JSON_PATH, text);
    expect(readFileSync(JSON_PATH, "utf8")).toBe(text);
  });

  it("covers every action and catalog row", () => {
    for (const r of rows) expect(generated[r.key]).toBeDefined();
  });
});

describe("open-weights classifier", () => {
  it("region restriction is exactly the MiniMax H3 families", () => {
    const ids = MODEL_FAMILIES.filter(isRegionRestrictedFamily).map(
      (f) => f.id,
    );
    expect(ids.sort()).toEqual([
      "h3",
      "h3-latent-upscaler",
      "open-h3-regenerate",
      "pika-h3-flex",
      "qwen3vl-h3",
    ]);
  });

  it("nc beats region; revenue-capped community licenses are cap", () => {
    const fam = (id: string) => MODEL_FAMILIES.find((f) => f.id === id)!;
    const h3 = fam("h3");
    const krea = fam("krea2");
    expect(classifyDocRow({ commercial: "restricted", families: [h3] })).toBe(
      "region",
    );
    expect(classifyDocRow({ commercial: "no", families: [h3] })).toBe("nc");
    expect(classifyDocRow({ commercial: "restricted", families: [krea] })).toBe(
      "cap",
    );
    expect(
      classifyDocRow({ commercial: "restricted", families: [krea, h3] }),
    ).toBe("region");
    // Gemma terms / AGPL runtime: commercial use allowed, so Open.
    expect(familyBadge(fam("gemma4-ltx"))).toBe("open");
    expect(familyBadge(fam("yolov8"))).toBe("open");
    for (const id of ["krea2", "flux3", "ltx-25", "ltxv-098", "stable-audio-3"])
      expect([id, familyBadge(fam(id))]).toEqual([id, "cap"]);
    for (const id of ["krea2-control", "hdemucs"])
      expect([id, familyBadge(fam(id))]).toEqual([id, "check"]);
    // A check-license family always links somewhere to read.
    for (const f of MODEL_FAMILIES)
      if (familyBadge(f) === "check") expect(f.url, f.id).toMatch(/^https:/);
  });

  it("hub cards follow the generated classes (hub nc flag only tightens)", () => {
    for (const [key, cls] of Object.entries(generated)) {
      const card = byKey.get(key);
      if (!card) continue; // outpaint backends fold into one card
      expect([key, weightsClass(card)]).toEqual([key, card.nc ? "nc" : cls]);
    }
  });

  it("only optional picker modes relax a toolsDoc row", () => {
    const relaxed = rows
      .filter((r) => generated[r.key] !== classifyDocRow(r))
      .map((r) => r.key);
    // Motion presets runs on Wan 2.2; a few presets use the optional H3 pack.
    // Upscale video's default engines are open; its optional LTX x2 engine
    // (LTX-2 Community License) shows on the doc row and its own option.
    expect(relaxed).toEqual(["action:upscale_video", "action:wan_motion"]);
    for (const r of rows)
      if (r.commercial === "no" && r.key !== "action:wan_motion")
        expect([r.key, generated[r.key]]).toEqual([r.key, "nc"]);
  });

  it("classifies known cards", () => {
    const cls = (k: string) => weightsClass(byKey.get(k)!);
    expect(cls("action:face_swap")).toBe("region");
    expect(cls("action:transition")).toBe("region");
    expect(weightsTooltip(byKey.get("action:face_swap")!)).toMatch(
      /European Union, the United Kingdom, the Republic of Korea or the United States of America/,
    );
    expect(cls("action:describe")).toBe("open");
    expect(cls("catalog:krea2-restyle-depth")).toBe("check");
    expect(cls("catalog:krea2-general-edit")).toBe("nc");
    expect(cls("catalog:flux3-restore")).toBe("cap");
    // SAM 3.1 is commercial-OK (Meta SAM License), so breakdown is open.
    expect(cls("action:breakdown")).toBe("open");
    expect(cls("action:edit_fibo")).toBe("nc");
    expect(cls("action:add_sound")).toBe("nc");
    expect(cls("action:video_edit")).toBe("nc");
    expect(cls("action:edit_qwen21")).toBe("nc");
    expect(cls("action:upscale")).toBe("open");
    expect(cls("special:color_grade")).toBe("open");
    expect(cls("action:wan_motion")).toBe("open");
    // Outpaint runs the fastest installed backend: the best one decides.
    const outpaint = byKey.get("catalog:outpaint")!;
    const best = generated["catalog:outpaint"];
    expect(cls(outpaint.key)).toBe(outpaint.nc ? "nc" : best);
    expect(weightsClass({ ...outpaint, nc: false })).toBe(best);
  });

  it("engine cards: nc only when every engine is nc", () => {
    for (const t of TEMPLATES) {
      const c = weightsClass(byKey.get(`template:${t.id}`)!);
      expect(c).not.toBe("region");
    }
    for (const a of APP_TEMPLATES) {
      const card = byKey.get(`app:${a.id}`)!;
      const c = weightsClass(card);
      if (a.sound && a.autoAnimate) expect(c).toBe("nc");
      else expect(["open", "cap", "nc"]).toContain(c);
    }
  });

  it("engine cards follow their nc flag (the engine that actually runs)", () => {
    const storyboard = byKey.get("special:storyboard")!;
    if (storyboard.nc) expect(weightsClass(storyboard)).toBe("nc");
    else expect(["open", "cap"]).toContain(weightsClass(storyboard));
    expect(weightsClass({ ...storyboard, nc: true })).toBe("nc");
    const engineCards = cards.filter(
      (c) =>
        c.kind === "template" ||
        c.kind === "app" ||
        c.key === "special:storyboard",
    );
    expect(engineCards.length).toBeGreaterThan(0);
    for (const c of engineCards) {
      if (c.nc) expect([c.key, weightsClass(c)]).toEqual([c.key, "nc"]);
      expect(weightsClass({ ...c, nc: true })).toBe("nc");
    }
  });

  it("no card shows the nc badge and the open-weights chip together", () => {
    for (const c of cards)
      if (c.nc) expect([c.key, isOpenWeights(c)]).toEqual([c.key, false]);
  });

  it("every card gets a class", () => {
    for (const c of cards)
      expect(["open", "cap", "nc", "region", "check"]).toContain(
        weightsClass(c),
      );
  });

  it("no tooltip says unverified; cap and region tooltips state real terms", () => {
    for (const c of cards) {
      if (c.kind === "placeholder") continue;
      const t = weightsTooltip(c);
      expect([c.key, /unverified|restricted/i.test(t)]).toEqual([c.key, false]);
      const b = weightsClass(c);
      if (b === "cap")
        expect([c.key, /US\$\d+M/.test(t)]).toEqual([c.key, true]);
      if (b === "region")
        expect([c.key, /Republic of Korea/.test(t)]).toEqual([c.key, true]);
    }
  });
});

describe("open-weights count + filter", () => {
  it("counts real tools, not placeholders", () => {
    const { open, total } = openWeightsCount(cards);
    const tools = cards.filter((c) => c.kind !== "placeholder");
    expect(total).toBe(tools.length);
    expect(open).toBe(
      tools.filter((c) => ["open", "cap"].includes(weightsClass(c))).length,
    );
    expect(open).toBeGreaterThan(0);
    expect(open).toBeLessThan(total);
    expect(openWeightsSummary(cards)).toBe(
      `${open} of ${total} tools allow commercial use`,
    );
  });

  it("filter keeps Open + Revenue cap tools and placeholders only", () => {
    expect(filterOpenWeights(cards, false)).toBe(cards);
    const kept = filterOpenWeights(cards, true);
    const placeholders = cards.filter((c) => c.kind === "placeholder").length;
    expect(kept.length).toBe(openWeightsCount(cards).open + placeholders);
    expect(kept.some((c) => c.key === "action:face_swap")).toBe(false);
    expect(kept.some((c) => c.key === "action:edit_fibo")).toBe(false);
    expect(kept.some((c) => c.key === "action:describe")).toBe(true);
    expect(kept.some((c) => c.key === "catalog:flux3-restore")).toBe(true);
  });

  it("counts a small hand-built set", () => {
    const base = byKey.get("special:color_grade")!;
    const set: HubCard[] = [
      base,
      { ...base, key: "x:nc", nc: true },
      { ...base, key: "x:h3", model: "MiniMax H3" },
      { ...base, key: "x:soon", kind: "placeholder" },
    ];
    expect(openWeightsCount(set)).toEqual({ open: 1, total: 3 });
    expect(openWeightsSummary(set)).toBe("1 of 3 tools allow commercial use");
  });
});

describe("open-weights persistence", () => {
  it("round-trips and never throws", () => {
    const m = new Map<string, string>();
    const s = {
      getItem: (k: string) => m.get(k) ?? null,
      setItem: (k: string, v: string) => void m.set(k, v),
    };
    expect(readOpenWeightsOnly(s)).toBe(false);
    writeOpenWeightsOnly(s, true);
    expect(m.get(OPEN_WEIGHTS_STORAGE_KEY)).toBe("1");
    expect(readOpenWeightsOnly(s)).toBe(true);
    writeOpenWeightsOnly(s, false);
    expect(readOpenWeightsOnly(s)).toBe(false);
    const broken = {
      getItem: () => {
        throw new Error("blocked");
      },
      setItem: () => {
        throw new Error("blocked");
      },
    };
    expect(readOpenWeightsOnly(broken)).toBe(false);
    expect(() => writeOpenWeightsOnly(broken, true)).not.toThrow();
    expect(readOpenWeightsOnly(null)).toBe(false);
  });
});
