"use client";

import { useEffect, useMemo, useRef, useState } from "react";
import { Music, Square } from "lucide-react";
import { useGenerationStore } from "@/store";
import { showToast } from "@/components/Toast";
import type { EngineContext } from "@/lib/tools/templates";
import type { HubCard } from "@/lib/tools/hub";
import type { ToolAudio, ToolImage } from "@/lib/tools/runTool";
import { analyzeAudioUrl, type BeatAnalysis } from "@/lib/tools/beats";
import {
  MV_ASPECTS,
  MV_MAX_REFS,
  MV_MAX_SECONDS,
  MV_MIN_SECONDS,
  MV_SEGMENT_CHOICES,
  planMusicVideo,
  stemsAvailable,
  type MvAspect,
  type MvModelStatus,
  type MvPlan,
} from "@/lib/tools/musicVideo";
import {
  runMusicVideo,
  runMusicVideoStems,
  uploadSong,
  type MvResult,
  type MvStems,
} from "@/lib/tools/musicVideoRunner";
import { RunFooter, RunnerShell, errorMessage } from "./RunnerShell";
import { Segmented } from "./ToolRunner";
import { measureMedia } from "./DubRunner";
import { ToolImageInput } from "./ToolImageInput";
import { ToolAudioInput } from "./ToolAudioInput";
import { H3Attribution, LikenessConsent, useLikenessConsent } from "./H3Notice";

const inputCls =
  "w-full rounded-xl border border-light-100 bg-transparent px-3 py-2 text-sm dark:border-dark-750";

/**
 * Music Video (MiniMax H3 pack): a song + 1-3 character / style images ->
 * beat-cut segments, each generated by H3 Ref2VA to its slice of the song
 * and continuing from the previous segment's last frame, joined under the
 * original song. Optional Demucs stems: drum-stem beats, vocal-stem
 * lip-sync segments.
 */
export function MusicVideoRunner({
  card,
  onBack,
  modelStatus,
}: {
  card: HubCard;
  ctx: EngineContext;
  onBack: () => void;
  modelStatus?: MvModelStatus | null;
}) {
  const clientId = useGenerationStore((s) => s.clientId);
  const addRun = useGenerationStore((s) => s.addRun);
  const [song, setSong] = useState<ToolAudio | null>(null);
  const [refs, setRefs] = useState<(ToolImage | null)[]>([null]);
  const [style, setStyle] = useState("");
  const [target, setTarget] = useState("5");
  const [start, setStart] = useState("0");
  const [length, setLength] = useState("");
  const [aspect, setAspect] = useState<MvAspect>("16:9");
  const [beats, setBeats] = useState<BeatAnalysis | null>(null);
  const [analyzing, setAnalyzing] = useState(false);
  const [stems, setStems] = useState<MvStems | null>(null);
  const [stemBeats, setStemBeats] = useState<BeatAnalysis | null>(null);
  const [stemsWindow, setStemsWindow] = useState<string | null>(null);
  const [shots, setShots] = useState<string[]>([]);
  const [lipsync, setLipsync] = useState<boolean[]>([]);
  const [busy, setBusy] = useState(false);
  const [status, setStatus] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [clips, setClips] = useState<string[]>([]);
  const [result, setResult] = useState<MvResult | null>(null);
  const [consented, setConsented] = useLikenessConsent(card.key);
  const cancelled = useRef(false);
  const canStem = stemsAvailable(modelStatus);

  useEffect(() => {
    setBeats(null);
    setStems(null);
    setStemBeats(null);
    if (!song) return;
    let live = true;
    setAnalyzing(true);
    analyzeAudioUrl(song.previewUrl)
      .then((a) => live && setBeats(a))
      .catch(() => live && setBeats(null))
      .finally(() => live && setAnalyzing(false));
    return () => {
      live = false;
    };
  }, [song]);

  const duration = song?.duration ?? null;
  const windowKey = `${start}|${length}`;
  // Stems are cut to the window they were made for.
  const stemsFresh = !!stems && stemsWindow === windowKey;
  const planned = useMemo((): { plan: MvPlan | null; err: string | null } => {
    if (!song || duration === null || analyzing)
      return { plan: null, err: null };
    try {
      const useStem = stemsFresh && !!stemBeats;
      const plan = planMusicVideo({
        duration,
        start: Number(start) || 0,
        seconds: length.trim() ? Number(length) : undefined,
        beats: useStem ? stemBeats!.beats : (beats?.beats ?? []),
        onsets: useStem ? stemBeats!.onsets : (beats?.onsets ?? []),
        beatsInWindow: useStem,
        bpm: (useStem ? stemBeats?.bpm : beats?.bpm) ?? null,
        target: Number(target),
      });
      return { plan, err: null };
    } catch (e) {
      return { plan: null, err: errorMessage(e) };
    }
  }, [
    song,
    duration,
    analyzing,
    start,
    length,
    beats,
    stemBeats,
    stemsFresh,
    target,
  ]);
  const plan = planned.plan;

  const refData = refs.filter((r): r is ToolImage => !!r?.dataUrl);
  const validation = !song
    ? "Add a song."
    : duration === null
      ? "Couldn't read the song length."
      : duration < MV_MIN_SECONDS
        ? `The song is under ${MV_MIN_SECONDS} s.`
        : analyzing
          ? "Finding the beats..."
          : planned.err
            ? planned.err
            : !refData.length
              ? "Add a character or style image."
              : !consented
                ? "Confirm the likeness consent."
                : null;

  const deps = () => ({
    fetchImpl: fetch,
    clientId,
    onRun: addRun,
    measure: measureMedia,
    isCancelled: () => cancelled.current,
  });

  const splitStems = async () => {
    if (!song || !plan) return;
    cancelled.current = false;
    setBusy(true);
    setError(null);
    setStatus("Separating stems...");
    try {
      const d = deps();
      const songRef = stems?.songRef ?? (await uploadSong(song, d));
      const s = await runMusicVideoStems(
        songRef,
        { start: plan.start, seconds: plan.seconds },
        d,
      );
      setStems(s);
      setStemsWindow(windowKey);
      setStemBeats(
        s.drums ? await analyzeAudioUrl(s.drums.url).catch(() => null) : null,
      );
      showToast("Stems ready: cuts follow the drums.", "success");
    } catch (e) {
      if (!cancelled.current) setError(errorMessage(e));
    } finally {
      setBusy(false);
      setStatus(null);
    }
  };

  const go = async () => {
    if (!song || !plan) return;
    cancelled.current = false;
    setBusy(true);
    setError(null);
    setResult(null);
    setClips([]);
    try {
      const d = deps();
      setStatus("Uploading...");
      const songRef = stems?.songRef ?? (await uploadSong(song, d));
      const res = await runMusicVideo(
        {
          songRef,
          refs: refData.map((r) => ({ dataUrl: r.dataUrl! })),
          plan,
          vocalsRef: stemsFresh ? (stems?.vocals?.ref ?? null) : null,
        },
        {
          style,
          shots,
          lipsync: stemsFresh ? lipsync : [],
          aspect,
        },
        d,
        (p) => {
          if (p.phase === "segment")
            setStatus(`Segment ${(p.index ?? 0) + 1} of ${p.total}...`);
          if (p.phase === "assemble") setStatus("Joining with the song...");
          if (p.clip) setClips((c) => [...c, p.clip!.url]);
        },
      );
      setResult(res);
      showToast(`${card.title}: done.`, "success");
    } catch (e) {
      if (cancelled.current) showToast("Stopped.", "info");
      else setError(errorMessage(e));
    } finally {
      setBusy(false);
      setStatus(null);
    }
  };

  const beatNote = !song
    ? `Up to ${MV_MAX_SECONDS} s of the song; cuts land on its beats (bar lines first).`
    : analyzing
      ? "Finding the beats..."
      : stemsFresh && stemBeats
        ? `Drum stem: ${Math.round(stemBeats.bpm)} BPM, ${stemBeats.beats.length} beats.`
        : beats && beats.confidence > 0
          ? `${Math.round(beats.bpm)} BPM, ${beats.beats.length} beats found.`
          : "No clear beat found; cuts follow a steady 120 BPM grid.";

  return (
    <RunnerShell
      title={card.title}
      subtitle={card.subtitle}
      model={card.model}
      blockedReason={card.available ? null : card.unavailableReason}
      checking={card.checking}
      onBack={onBack}
      testId="music-video"
    >
      <H3Attribution />
      <fieldset disabled={busy} className="space-y-4">
        <ToolAudioInput
          label="Song"
          value={song}
          onChange={setSong}
          note={beatNote}
        />
        <div className="grid grid-cols-2 gap-3">
          <label className="space-y-1 text-xs">
            <span>Start (s)</span>
            <input
              className={inputCls}
              inputMode="decimal"
              value={start}
              onChange={(e) => setStart(e.target.value)}
            />
          </label>
          <label className="space-y-1 text-xs">
            <span>Length (s, max {MV_MAX_SECONDS})</span>
            <input
              className={inputCls}
              inputMode="decimal"
              placeholder="to the end"
              value={length}
              onChange={(e) => setLength(e.target.value)}
            />
          </label>
        </div>
        {refs.map((r, i) => (
          <ToolImageInput
            key={i}
            label={
              i === 0 ? "Character / style 1" : `Character / style ${i + 1}`
            }
            value={r}
            onChange={(v) =>
              setRefs((rs) => rs.map((x, j) => (j === i ? v : x)))
            }
            needsPixels
          />
        ))}
        {refs.length < MV_MAX_REFS && (
          <button
            type="button"
            className="text-xs underline"
            onClick={() => setRefs((rs) => [...rs, null])}
          >
            Add another image
          </button>
        )}
        <label className="block space-y-1 text-xs">
          <span>Style (every segment)</span>
          <textarea
            className={inputCls}
            rows={2}
            maxLength={600}
            placeholder="neon-lit city at night, handheld camera, film grain"
            value={style}
            onChange={(e) => setStyle(e.target.value)}
          />
        </label>
        <Segmented
          label="Segment length"
          value={target}
          options={MV_SEGMENT_CHOICES.map((s) => ({
            id: String(s),
            label: `~${s} s`,
          }))}
          onChange={setTarget}
        />
        <Segmented
          label="Aspect"
          value={aspect}
          options={MV_ASPECTS.map((a) => ({ id: a, label: a }))}
          onChange={(v) => setAspect(v as MvAspect)}
        />
        {canStem && plan && (
          <div className="space-y-1 text-xs">
            <button
              type="button"
              className="rounded-xl border border-light-100 px-3 py-1.5 dark:border-dark-750"
              onClick={() => void splitStems()}
            >
              {stemsFresh
                ? "Stems ready (redo)"
                : "Separate stems (drums + vocals)"}
            </button>
            <p className="text-light-500 dark:text-dark-400">
              Optional. Cuts follow the drum stem; lip-sync segments hear the
              vocals only.
            </p>
          </div>
        )}
        {plan && (
          <div className="space-y-2" data-testid="music-video-plan">
            <p className="text-xs text-light-500 dark:text-dark-400">
              {plan.segments.length} segment
              {plan.segments.length === 1 ? "" : "s"}, {plan.seconds} s from{" "}
              {plan.start} s.
            </p>
            {plan.segments.map((s) => (
              <div key={s.index} className="flex items-center gap-2 text-xs">
                <span className="w-24 shrink-0 tabular-nums">
                  {s.start.toFixed(2)}-{s.end.toFixed(2)} s
                </span>
                <input
                  className={inputCls}
                  maxLength={600}
                  placeholder="Shot (optional)"
                  aria-label={`Segment ${s.index + 1} shot`}
                  value={shots[s.index] ?? ""}
                  onChange={(e) =>
                    setShots((xs) => {
                      const n = [...xs];
                      n[s.index] = e.target.value;
                      return n;
                    })
                  }
                />
                {stemsFresh && stems?.vocals && (
                  <label className="flex shrink-0 items-center gap-1">
                    <input
                      type="checkbox"
                      checked={!!lipsync[s.index]}
                      onChange={(e) =>
                        setLipsync((xs) => {
                          const n = [...xs];
                          n[s.index] = e.target.checked;
                          return n;
                        })
                      }
                    />
                    Lip-sync
                  </label>
                )}
              </div>
            ))}
          </div>
        )}
        <LikenessConsent checked={consented} onChange={setConsented} />
      </fieldset>

      <div className="flex flex-wrap items-start gap-2">
        <RunFooter
          label="Make music video"
          busy={busy}
          disabled={!card.available}
          validation={validation}
          error={error}
          queuedText={status}
          onRun={() => void go()}
          icon={<Music className="h-4 w-4" />}
        />
        {busy && (
          <button
            type="button"
            onClick={() => {
              cancelled.current = true;
            }}
            className="flex items-center gap-1.5 rounded-xl border border-light-100 px-4 py-2.5 text-sm dark:border-dark-750"
          >
            <Square className="h-3.5 w-3.5" /> Stop after this step
          </button>
        )}
      </div>

      {!result && clips.length > 0 && (
        <section
          className="grid grid-cols-2 gap-2"
          data-testid="music-video-clips"
        >
          {clips.map((u) => (
            <video
              key={u}
              src={u}
              controls
              playsInline
              className="rounded-xl"
            />
          ))}
        </section>
      )}
      {result && (
        <section className="space-y-3" data-testid="music-video-result">
          <video
            src={result.video.url}
            controls
            playsInline
            className="mx-auto max-h-[70vh] rounded-xl"
            data-testid="music-video-video"
          />
        </section>
      )}
    </RunnerShell>
  );
}
